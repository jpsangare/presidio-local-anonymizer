async function getUiLanguage() {
  const stored = await chrome.storage.local.get('uiLanguage');
  return SUPPORTED_UI_LANGUAGES.includes(stored.uiLanguage)
    ? stored.uiLanguage
    : DEFAULT_UI_LANGUAGE;
}

function extensionText(key, language = DEFAULT_UI_LANGUAGE, values = {}) {
  const template = UI_TRANSLATIONS[language]?.[key] || UI_TRANSLATIONS[DEFAULT_UI_LANGUAGE][key] || key;
  return template.replace(/\{(\w+)\}/g, (_, name) => values[name] ?? '');
}

function translateOptionsDocument(language) {
  const translations = UI_TRANSLATIONS[language]?.optionsText || {};
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  let node;

  while ((node = walker.nextNode())) {
    const source = node.nodeValue.trim();
    if (!source || !translations[source]) continue;

    const leadingWhitespace = node.nodeValue.match(/^\s*/)[0];
    const trailingWhitespace = node.nodeValue.match(/\s*$/)[0];
    node.nodeValue = `${leadingWhitespace}${translations[source]}${trailingWhitespace}`;
  }

  document.documentElement.lang = language;
  document.title = extensionText('optionsTitle', language);

  const title = document.querySelector('body > .container > h1');
  if (title) title.textContent = extensionText('configure', language);
}
